// Builds the public site into site/dist: the landing page from src/index.html, and the docs from
// README.md and docs/framework.md, so the site says what the kit does at the commit it was built from.
//   node site/build.mjs
import { Marked } from "marked";
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const SITE = dirname(fileURLToPath(import.meta.url));
const KIT = join(SITE, "..");
const DIST = join(SITE, "dist");
const REPO_URL = "https://github.com/alopezari/agents-kit";
const MERMAID_URL = "https://cdn.jsdelivr.net/npm/mermaid@12.0.0/dist/mermaid.esm.min.mjs";
// README sections that belong in the docs, and where: the rest of the README is covered by the reference.
const README_BEFORE = ["Install", "Make it yours"];
const README_AFTER = ["Hook contract", "Adding a harness"];

const read = (path) => readFileSync(join(KIT, path), "utf8");

function fill(template, values) {
  return template.replace(/\{\{(\w+)\}\}/g, (_, key) => {
    if (!(key in values)) throw new Error(`no value for {{${key}}}`);
    return values[key];
  });
}

function match(text, pattern, what) {
  const found = text.match(pattern);
  if (!found) throw new Error(`could not find ${what} (${pattern}); did the source wording change?`);
  return found[1];
}

// "## Heading" sections of a Markdown file, keyed by heading text.
function sections(markdown) {
  const parts = {};
  for (const chunk of markdown.split(/^(?=## )/m).slice(1)) {
    parts[chunk.match(/^## (.+)$/m)[1].trim()] = chunk.trimEnd() + "\n";
  }
  return parts;
}

const slug = (text) => text.toLowerCase().replace(/<[^>]+>/g, "").replace(/&[a-z]+;/g, "")
  .replace(/[^a-z0-9\s-]/g, "").trim().replace(/\s+/g, "-");

function renderDocs(markdown) {
  const nav = [];
  const escape = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
  const marked = new Marked({
    gfm: true,
    renderer: {
      heading({ tokens, depth }) {
        const html = this.parser.parseInline(tokens);
        const id = slug(html);
        if (depth === 2) nav.push(`<li><a href="#${id}">${html}</a></li>`);
        const anchor = depth > 1 ? `<a class="anchor" href="#${id}" aria-label="Link to this section">¶</a>` : "";
        return `<h${depth} id="${id}">${html}${anchor}</h${depth}>\n`;
      },
      code({ text, lang }) {
        if (lang === "mermaid") return `<div class="mermaid-wrap" tabindex="0"><pre class="mermaid">${escape(text)}</pre></div>\n`;
        return `<pre tabindex="0"><code>${escape(text)}</code></pre>\n`;
      },
      link({ href, title, tokens }) {
        // Relative links point into the repository, which the site doesn't carry.
        const target = /^(https?:|mailto:|#)/.test(href) ? href : `${REPO_URL}/blob/main/${href.replace(/^\.\//, "")}`;
        const titleAttr = title ? ` title="${escape(title)}"` : "";
        return `<a href="${target}"${titleAttr}>${this.parser.parseInline(tokens)}</a>`;
      },
    },
  });
  const html = marked.parse(markdown)
    .replace(/<table>/g, '<div class="table-wrap" tabindex="0"><table>').replace(/<\/table>/g, "</table></div>");
  return { html, nav: nav.join("") };
}

function docsMarkdown() {
  const framework = read("docs/framework.md")
    .replace(/^_Generated by .*_\n\n/m, "");
  const readme = sections(read("README.md"));
  const [head, ...rest] = framework.split(/^(?=## )/m);
  const glance = rest.shift();
  if (!glance.startsWith("## At a glance")) throw new Error("docs/framework.md no longer opens with 'At a glance'");
  const pick = (names) => names.map((name) => {
    if (!readme[name]) throw new Error(`README.md has no '## ${name}' section`);
    return readme[name];
  }).join("\n");
  return [head, glance, pick(README_BEFORE), ...rest, pick(README_AFTER)].join("\n");
}

function main() {
  const framework = read("docs/framework.md");
  const guardRules = Number(match(framework, /\*\*(\d+) guard rules\*\*/, "the guard rule count"));
  const stats = {
    harnesses: match(framework, /\*\*(\d+) harnesses\*\*/, "the harness count"),
    guard_rules: String(guardRules),
    stacks: match(framework, /\*\*(\d+) stacks\*\*/, "the stack count"),
    review_comments: match(read("AGENTS.md"), /analysis of ~([\d,]+) human code-review comments/, "the review comment count"),
    // The landing page shows seven rules by name.
    more_rules: String(guardRules - 7),
  };
  const svg = (name) => readFileSync(join(SITE, "src", "svg", name), "utf8").trim();

  rmSync(DIST, { recursive: true, force: true });
  mkdirSync(join(DIST, "docs"), { recursive: true });

  const landing = fill(readFileSync(join(SITE, "src", "index.html"), "utf8"), {
    ...stats, repo_url: REPO_URL,
    flow_svg: svg("flow.svg"), flow_svg_narrow: svg("flow-narrow.svg"),
    architecture_svg: svg("architecture.svg"), loop_svg: svg("loop.svg"),
  });
  writeFileSync(join(DIST, "index.html"), landing);

  const docs = renderDocs(docsMarkdown());
  for (const anchor of [...landing.matchAll(/href="docs\/#([^"]+)"/g)].map((m) => m[1])) {
    if (!docs.html.includes(`id="${anchor}"`)) throw new Error(`the landing page links to docs/#${anchor}, which doesn't exist`);
  }
  writeFileSync(join(DIST, "docs", "index.html"), fill(readFileSync(join(SITE, "src", "docs.html"), "utf8"), {
    content: docs.html, nav: docs.nav, repo_url: REPO_URL, mermaid_url: MERMAID_URL,
    built: new Date().toISOString().slice(0, 10),
  }));

  cpSync(join(SITE, "src", "styles.css"), join(DIST, "styles.css"));
  cpSync(join(SITE, "src", "favicon.svg"), join(DIST, "favicon.svg"));
  console.log(`built ${DIST}: landing (${Object.entries(stats).map(([k, v]) => `${k}=${v}`).join(", ")}) and docs`);
}

main();
